
def generate_quality_report(original_df, result):

    summary = result["summary"]
    total_rows = len(original_df)

    # 1. Calculate completeness
    total_cells = original_df.size
    missing_cells = int(original_df.isna().sum().sum())

    completeness = (
        ((total_cells - missing_cells) / total_cells) * 100
        if total_cells else 100
    )

    # 2. Calculate duplicate percentage
    duplicate_rows = int(original_df.duplicated().sum())

    duplicate_rate = (
        (duplicate_rows / total_rows) * 100
        if total_rows else 0
    )

    # 3. Calculate validity percentage
    cleaned_rows = summary["cleaned_rows"]
    valid_records = summary["valid_records"]

    validity = (
        (valid_records / cleaned_rows) * 100
        if cleaned_rows else 100
    )

    # 4. Calculate overall quality score
    duplicate_free_score = 100 - duplicate_rate

    quality_score = round(
        (completeness * 0.40)
        + (duplicate_free_score * 0.20)
        + (validity * 0.40),
        2
    )

    # 5. Assign quality grade
    if quality_score >= 90:
        grade = "Excellent"
    elif quality_score >= 75:
        grade = "Good"
    elif quality_score >= 50:
        grade = "Needs Improvement"
    else:
        grade = "Poor"

    # 6. Identify problems
    issues = []
    recommendations = []

    if missing_cells > 0:
        issues.append(
            f"{missing_cells} missing cells found."
        )
        recommendations.append(
            "Review missing values and apply suitable "
            "default values or business rules."
        )

    if duplicate_rows > 0:
        issues.append(
            f"{duplicate_rows} duplicate rows found."
        )
        recommendations.append(
            "Remove duplicate records using appropriate "
            "business keys."
        )

    rejected_records = summary["rejected_records"]

    if rejected_records > 0:
        issues.append(
            f"{rejected_records} records failed validation."
        )
        recommendations.append(
            "Review rejected records and correct the "
            "validation errors."
        )

    if not issues:
        issues.append(
            "No major data quality issues detected."
        )
        recommendations.append(
            "Continue monitoring data quality during "
            "future pipeline executions."
        )

    # 7. Generate report text
    report_text = f"""
SMARTETL AI - DATA QUALITY REPORT

========================================

OVERALL DATA QUALITY

Quality Score: {quality_score}%
Quality Grade: {grade}

DATASET INFORMATION

Total Input Rows: {summary['total_input_rows']}
Cleaned Rows: {summary['cleaned_rows']}
Valid Records: {summary['valid_records']}
Rejected Records: {summary['rejected_records']}

DATA QUALITY METRICS

Completeness: {round(completeness, 2)}%
Duplicate Rate: {round(duplicate_rate, 2)}%
Validity Rate: {round(validity, 2)}%

IDENTIFIED ISSUES

{chr(10).join('- ' + issue for issue in issues)}

RECOMMENDATIONS

{chr(10).join('- ' + item for item in recommendations)}

========================================
Report generated by SmartETL AI
"""

    return {
        "quality_score": quality_score,
        "grade": grade,
        "completeness": round(completeness, 2),
        "duplicate_rate": round(duplicate_rate, 2),
        "validity": round(validity, 2),
        "issues": issues,
        "recommendations": recommendations,
        "report_text": report_text
    }
